import { Link } from "react-router-dom";
import type { Decision, StrategySummary } from "../../api/types";
import { useApi } from "../../components/hooks";
import { Card, ErrorState, Loading, PageHeader, Stat, StatusBadge, fmt } from "../../components/ui";

interface Overview {
  pending_proposals: number;
  planning_requests: number;
  approved_strategies: number;
  rejected_strategies: number;
  revision_requests: number;
  users: number;
  recent_decisions: Decision[];
  approved_reference_strategy: StrategySummary | null;
}

export default function AdminDashboard() {
  const { data, loading, error, reload } = useApi<Overview>("/api/admin/overview");
  if (loading) return <Loading />;
  if (error || !data) return <ErrorState message={error ?? "No data"} onRetry={reload} />;
  return (
    <>
      <PageHeader eyebrow="Administration" title="Administrator dashboard" subtitle="Review strategy proposals generated by the agent. No strategy is approved without an administrator decision."
        actions={<Link to="/admin/review" className="btn-gold">Open review queue ({data.pending_proposals})</Link>} />
      <div className="grid grid-cols-2 gap-4 lg:grid-cols-5">
        <Stat label="Pending proposals" value={data.pending_proposals} accent />
        <Stat label="Planning requests" value={data.planning_requests} />
        <Stat label="Approved strategies" value={data.approved_strategies} />
        <Stat label="Rejected strategies" value={data.rejected_strategies} />
        <Stat label="Revision requests" value={data.revision_requests} />
      </div>
      <div className="mt-6 grid gap-6 xl:grid-cols-2">
        <Card title="Current planning reference">
          {data.approved_reference_strategy ? (
            <Link to={`/strategies/${data.approved_reference_strategy.id}`} className="block rounded-lg border border-gold/60 bg-gold-light/40 p-4">
              <div className="font-semibold">{data.approved_reference_strategy.name} v{data.approved_reference_strategy.version}</div>
              <div className="mt-1 text-sm text-ink-soft">{data.approved_reference_strategy.strategic_objective}</div>
            </Link>
          ) : <p className="text-sm text-ink-soft">No approved strategy yet.</p>}
        </Card>
        <Card title="Recent decisions" actions={<Link to="/admin/decisions" className="text-xs text-gold-dark hover:underline">Full audit trail</Link>}>
          {data.recent_decisions.length === 0 ? <p className="text-sm text-ink-soft">No decisions recorded.</p> : (
            <ul className="divide-y divide-line">
              {data.recent_decisions.map((d) => (
                <li key={d.id} className="flex items-center justify-between gap-3 py-2 text-sm">
                  <Link className="truncate hover:text-gold-dark" to={`/strategies/${d.strategy_id}`}>{d.strategy_name} v{d.strategy_version}</Link>
                  <span className="flex shrink-0 items-center gap-2"><StatusBadge status={d.decision} /><span className="text-[11px] text-ink-soft">{fmt.date(d.created_at)}</span></span>
                </li>
              ))}
            </ul>
          )}
        </Card>
      </div>
    </>
  );
}
