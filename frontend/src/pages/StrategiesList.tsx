import { Link, useSearchParams } from "react-router-dom";
import type { StrategySummary } from "../api/types";
import { useApi } from "../components/hooks";
import { DataStatusBadge, Empty, ErrorState, Loading, PageHeader, StatusBadge, fmt } from "../components/ui";

export function StrategyCards({ items }: { items: StrategySummary[] }) {
  return (
    <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3">
      {items.map((s) => (
        <Link key={s.id} to={`/strategies/${s.id}`} className={`card block p-5 transition hover:border-ink ${s.is_reference ? "border-gold ring-1 ring-gold/40" : ""}`}>
          <div className="flex items-start justify-between gap-2">
            <div>
              <div className="font-semibold">{s.name} <span className="text-xs font-normal text-ink-soft">v{s.version}</span></div>
              <div className="mt-0.5 line-clamp-2 text-xs text-ink-soft">{s.strategic_objective}</div>
            </div>
            <StatusBadge status={s.status} />
          </div>
          {(s.recommended || s.selected_by_requester || s.problem_type === "operational") && (
            <div className="mt-2 flex flex-wrap gap-1">
              {s.problem_type === "operational" && <span className="rounded-full border border-line px-2 py-0.5 text-[10px] font-semibold uppercase text-ink-soft">Operational</span>}
              {s.recommended && <span className="rounded-full bg-gold px-2 py-0.5 text-[10px] font-semibold text-ink">RECOMMENDED</span>}
              {s.selected_by_requester && <span className="rounded-full bg-ink px-2 py-0.5 text-[10px] font-semibold text-white">REQUESTER'S CHOICE</span>}
            </div>
          )}
          {s.headline?.kind === "operational" ? (
            <dl className="mt-4 grid grid-cols-2 gap-x-4 gap-y-2 text-sm">
              <div><dt className="text-xs text-ink-soft">Operating cost</dt><dd className="num font-medium">{fmt.num(s.headline.operating_cost_musd, 1)} MUSD</dd></div>
              <div><dt className="text-xs text-ink-soft">Unserved</dt><dd className="num font-medium">{fmt.num(s.headline.unserved_gwh, 1)} GWh</dd></div>
              <div><dt className="text-xs text-ink-soft">Gas generation</dt><dd className="num font-medium">{fmt.num(s.headline.gas_gwh)} GWh</dd></div>
              <div><dt className="text-xs text-ink-soft">Min reserve</dt><dd className="num font-medium text-gold-dark">{fmt.pct(s.headline.min_reserve_margin)}</dd></div>
            </dl>
          ) : s.headline ? (
            <dl className="mt-4 grid grid-cols-2 gap-x-4 gap-y-2 text-sm">
              <div><dt className="text-xs text-ink-soft">NPV cost</dt><dd className="num font-medium">{fmt.num(s.headline.total_cost_npv_musd)} MUSD</dd></div>
              <div><dt className="text-xs text-ink-soft">Investment</dt><dd className="num font-medium">{fmt.num(s.headline.total_investment_musd)} MUSD</dd></div>
              <div><dt className="text-xs text-ink-soft">CO2 cumulative</dt><dd className="num font-medium">{fmt.num(s.headline.total_emissions_mt, 1)} Mt</dd></div>
              <div><dt className="text-xs text-ink-soft">Renewables (final)</dt><dd className="num font-medium text-gold-dark">{fmt.pct(s.headline.renewable_share_final_year)}</dd></div>
            </dl>
          ) : <p className="mt-4 text-sm text-ink-soft">No validated solution.</p>}
          <div className="mt-4 flex items-center justify-between text-[11px] text-ink-soft">
            <span>{s.requester_email ?? fmt.date(s.created_at)}</span>
            <DataStatusBadge status={s.data_status} compact />
          </div>
          {s.duplicate_of && <div className="mt-2 text-[11px] text-ink-soft">Identical plan to “{s.duplicate_of}” — not submitted for review.</div>}
        </Link>
      ))}
    </div>
  );
}

export default function StrategiesList() {
  const [params] = useSearchParams();
  const request = params.get("request");
  const { data, loading, error, reload } = useApi<StrategySummary[]>(`/api/strategies${request ? `?request_id=${request}` : ""}`);
  return (
    <>
      <PageHeader eyebrow="Strategy generation results" title="Strategies"
        subtitle={request ? "Alternatives generated for one planning request — each has its own optimization run, roadmap and review status." : "All strategies generated by the planning agent that you can access."}
        actions={<>{request && <Link to="/strategies" className="btn-outline">All strategies</Link>}{data && data.filter((s) => s.run_id && s.feasible && s.problem_type !== "operational").length >= 2 && <Link to={`/compare?runs=${data.filter((s) => s.run_id && s.feasible && s.problem_type !== "operational").map((s) => s.run_id).join(",")}`} className="btn-gold">Compare side by side</Link>}</>} />
      {loading ? <Loading /> : error ? <ErrorState message={error} onRetry={reload} /> :
        data!.length === 0 ? <Empty title="No strategies yet" action={<Link className="btn-primary" to="/agent">Start a planning request</Link>}>Strategies are produced by the agent after you approve its formulation.</Empty> : <StrategyCards items={data!} />}
    </>
  );
}
